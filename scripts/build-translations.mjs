/**
 * Translation generation script for ICS E-Learning platform.
 * 
 * Reads all t() key-value pairs from all_t_keys_clean.txt,
 * preserves existing translations from translations.ts,
 * and generates missing translations for all 5 languages.
 * 
 * Usage: node scripts/build-translations.mjs
 */

import { readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');

// ── 1. Read all t() key → Vietnamese text pairs ──
const keysFile = readFileSync(join(__dirname, 'all_t_keys_utf8.txt'), 'utf-8');
const keyViPairs = {};
for (const line of keysFile.split('\n')) {
  const trimmed = line.trim();
  if (!trimmed) continue;
  const tabIdx = trimmed.indexOf('\t');
  if (tabIdx === -1) continue;
  const key = trimmed.substring(0, tabIdx).trim();
  const vi = trimmed.substring(tabIdx + 1).trim();
  if (key && vi) keyViPairs[key] = vi;
}
console.log(`Found ${Object.keys(keyViPairs).length} key-vi pairs from t() calls`);

