let stats = { total: allKeys.length, translated: {}, missing: {} };

for (const lang of languages) {
  output += `  ${lang.label}: {\n`;
  stats.translated[lang.code] = 0;
  stats.missing[lang.code] = 0;
  
  for (const key of allKeys) {
    let value;
    if (lang.code === 'vi') {
      // Vietnamese: use from t() calls or existing
      value = existingVi[key] || keyViPairs[key];
    } else {
      value = getTranslation(key, lang.code);
      if (!value) {
        // Fallback: use Vietnamese text (same as current behavior)
        value = keyViPairs[key] || existingVi[key];
        stats.missing[lang.code]++;
      } else {
        stats.translated[lang.code]++;
      }
    }
    
    if (value) {
      output += `    ${key}: '${escapeStr(value)}',\n`;
    }
  }
  
  output += `  },\n`;
}

output += `}\n`;

